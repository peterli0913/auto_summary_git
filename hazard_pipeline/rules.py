_COMPILED_SUB = {
    haz: {sub: [re.compile(p) for p in pats] for sub, pats in subs.items()}
    for haz, subs in SUBCLASS_KEYWORDS.items()
}


def rule_predict_subclass(hazard: str, text: str) -> Optional[str]:
    """在指定隐患类型下做关键词命中, 用于强标注."""
    if hazard == "其他":
        return "其他"
    if hazard not in _COMPILED_SUB:
        return None
    if not text:
        return None
    for sub, pats in _COMPILED_SUB[hazard].items():
        for pat in pats:
            if pat.search(text):
                return sub
    return None


# ------------------ 用于 train.py 的辅助函数 ------------------
def rule_features(text: str) -> Dict[str, int]:
    """把规则匹配作为额外特征 (0/1) 喂给模型, 提升判别."""
    text = text or ""
    feats = {}
    for label, pats in _COMPILED.items():
        feats[f"rule_haz_{label}"] = int(any(p.search(text) for p in pats))
    return feats
