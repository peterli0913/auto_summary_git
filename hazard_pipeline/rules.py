def _compile(patterns: Dict[str, List[str]]):
    return {k: [re.compile(p) for p in v] for k, v in patterns.items()}


_COMPILED = _compile(STRONG_KEYWORDS)


def rule_predict_hazard(text: str) -> Optional[str]:
    """命中即返回类别, 未命中返回 None."""
    if not text:
        return None
    hits = []
    for label in PER_TYPE_PRIORITY:
        for pat in _COMPILED[label]:
            if pat.search(text):
                hits.append(label)
                break
    if not hits:
        return None
    # 优先级: 正向类别优先于"其他"; 若文本既命中正类又命中"其他", 倾向正类
    for label in PER_TYPE_PRIORITY:
        if label != "其他" and label in hits:
            return label
    return hits[0]


